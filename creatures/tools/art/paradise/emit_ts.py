"""Writes the game's art data from the Python drawings: src/data/forms/baby.ts and land.ts (the creatures) and
src/art/field-land.ts (the Land field picture).

Usage:
  python3 emit_ts.py            write the files
  python3 emit_ts.py --check    write nothing; exit 1 if a file on disk differs from what the drawings give

A creature with any art problem (lib.problems), or a field that is not 128 x 128 or needs more than 62 colors, stops everything before
a single file is written (exit 3). The files are data, not code: redraw in Python and run this again instead of editing them by hand
(--check catches a hand edit). Needs Pillow (the field is drawn with it).
"""
import json
import os
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import land_all  # noqa: E402
import land_field  # noqa: E402
import lib  # noqa: E402

SRC = HERE.parents[2] / "src"
HEADER = (
    "// GENERATED by tools/art/paradise/emit_ts.py from the Python drawings. Do not edit by hand:\n"
    "// redraw in Python and run it again (`python3 emit_ts.py --check` finds a hand edit).\n"
)
# One file per place in the ladder: the baby has no field, and each field gets its own. Water and Sky join when their slices start.
FILES = [
    ("baby", [cr for cr in land_all.ROSTER if cr.stage == "baby"]),
    ("land", [cr for cr in land_all.ROSTER if cr.stage != "baby"]),
]
# A picture is written as a grid of palette letters, like every other sprite. 62 letters are enough for a field (the Land one uses 41).
LETTERS = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789"
FIELD_SIZE = 128


def value(v):
    """A Python value as TypeScript source, on one line. Keys that are plain words go unquoted."""
    if isinstance(v, dict):
        parts = [(k if k.isidentifier() else json.dumps(k)) + ": " + value(x) for k, x in v.items()]
        return "{ " + ", ".join(parts) + " }" if parts else "{}"
    if isinstance(v, (list, tuple)):
        return "[" + ", ".join(value(x) for x in v) + "]"
    if v is None:
        return "null"
    return json.dumps(v)  # strings (escaped) and numbers


def form_source(cr):
    b0, b1 = cr.body(0), cr.body(1)
    anchor = b0.anchor
    face = {"x": anchor.x, "y": anchor.y, "mouth": anchor.mouth}
    if b0.mouths:
        face["mouths"] = b0.mouths
    lines = [
        "  {",
        f"    id: {json.dumps(cr.id)},",
        f"    stage: {json.dumps(cr.stage)},",
        f"    name: {json.dumps(cr.name)},",
        f"    role: {json.dumps(cr.role)},",
        f"    palette: {value(cr.palette)},",
        f"    face: {value(face)},",
    ]
    for key, body in (("idle", b0), ("idle2", b1)):
        lines.append(f"    {key}: [")
        lines += [f"      {json.dumps(row)}," for row in body.canvas.rows()]
        lines.append("    ],")
    lines.append("  },")
    return "\n".join(lines)


def mouth_problems(cr):
    """lib.problems only stamps a custom mouth when a look uses it, so check its shape here: keys, dy, equal-width rows."""
    out = []
    for name, m in cr.body(0).mouths.items():
        rows = m.get("rows")
        if set(m) - {"x", "dy", "rows"} or not isinstance(m.get("dy"), int):
            out.append(f"{cr.id}: custom mouth {name} needs dy (an int) and may only have x, dy and rows")
        if not rows or len({len(r) for r in rows}) != 1:
            out.append(f"{cr.id}: custom mouth {name} needs rows of one width")
    return out


def field_source(name, im):
    """A field picture (a Pillow image) as TypeScript: a palette of letters and one row string per pixel row.
    Letters are given in the order the colors first appear, so the same picture always gives the same file."""
    if im.mode != "RGB":
        print(f"the {name} field is a {im.mode} picture, not RGB (a see-through pixel would be drawn solid), nothing written", file=sys.stderr)
        raise SystemExit(3)
    if im.size != (FIELD_SIZE, FIELD_SIZE):
        print(f"the {name} field is {im.size}, not {FIELD_SIZE} x {FIELD_SIZE}, nothing written", file=sys.stderr)
        raise SystemExit(3)
    letter_of = {}
    rows = []
    for y in range(FIELD_SIZE):
        row = ""
        for x in range(FIELD_SIZE):
            rgb = im.getpixel((x, y))[:3]
            if rgb not in letter_of:
                if len(letter_of) == len(LETTERS):
                    print(f"the {name} field needs more than {len(LETTERS)} colors, nothing written", file=sys.stderr)
                    raise SystemExit(3)
                letter_of[rgb] = LETTERS[len(letter_of)]
            row += letter_of[rgb]
        rows.append(row)
    palette = {letter: "#%02x%02x%02x" % rgb for rgb, letter in letter_of.items()}
    lines = [
        HEADER + 'import type { Sprite } from "./pixel";\n',
        f"// The {name} field: a {FIELD_SIZE} x {FIELD_SIZE} picture, drawn behind a creature that is out in it.",
        f"export const {name}Field: Sprite = {{",
        f"  palette: {value(palette)},",
        "  rows: [",
    ]
    lines += [f"    {json.dumps(row)}," for row in rows]
    lines += ["  ],", "};", ""]
    return "\n".join(lines)


def build():
    """{path under src/: text}. Raises (exit 3) if any creature has an art problem, and if an id is used twice."""
    bad = [p for _, roster in FILES for cr in roster for p in lib.problems(cr) + mouth_problems(cr)]
    if bad:
        print("art problems, nothing written:\n  " + "\n  ".join(bad), file=sys.stderr)
        raise SystemExit(3)
    ids = [cr.id for _, roster in FILES for cr in roster]
    twice = sorted({i for i in ids if ids.count(i) > 1})
    if twice:
        raise SystemExit(f"ids used twice: {twice}")
    files = {}
    for name, roster in FILES:
        body = "\n".join(form_source(cr) for cr in roster)
        files[f"data/forms/{name}.ts"] = (
            HEADER + 'import type { FormSource } from "../../game/types";\n\n'
            f"export const {name}: FormSource[] = [\n{body}\n];\n"
        )
    files["art/field-land.ts"] = field_source("land", land_field.background())
    return files


def main(argv):
    if argv not in ([], ["--check"]):
        print(__doc__)
        return 2
    files = build()
    if argv == ["--check"]:
        stale = [n for n, text in files.items() if not (SRC / n).exists() or (SRC / n).read_text() != text]
        print("stale: " + ", ".join(stale) if stale else "generated files match the drawings")
        return 1 if stale else 0
    # Write every file next to its place first, then swap them in, so a failure never leaves a half-updated pair.
    for n, text in files.items():
        (SRC / (n + ".tmp")).write_text(text)
    for n, text in files.items():
        os.replace(SRC / (n + ".tmp"), SRC / n)
        print(f"wrote {SRC / n} ({len(text)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
